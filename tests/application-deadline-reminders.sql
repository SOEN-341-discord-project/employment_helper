-- Use an empty disposable database. Create only the objects the reminder installation needs.
CREATE SCHEMA auth;
CREATE TABLE auth.users (
  id uuid PRIMARY KEY,
  raw_user_meta_data jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE TABLE public.recruiters (user_id uuid PRIMARY KEY REFERENCES auth.users(id));
CREATE TABLE public.jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  closing_date date,
  recruiter_id uuid REFERENCES auth.users(id)
);
CREATE TABLE public.applications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  applicant_id uuid NOT NULL REFERENCES auth.users(id),
  job_id bigint NOT NULL REFERENCES public.jobs(id),
  UNIQUE (applicant_id, job_id)
);
CREATE TABLE public.notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient_id uuid NOT NULL REFERENCES auth.users(id),
  type text NOT NULL,
  message text NOT NULL,
  job_id bigint REFERENCES public.jobs(id) ON DELETE CASCADE,
  application_id bigint REFERENCES public.applications(id) ON DELETE CASCADE,
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  available_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT notifications_type_check CHECK (type IN (
    'new_application', 'application_status', 'interview_invitation', 'interview_reminder', 'application_deadline'
  ))
);

-- A failure raises an exception; psql callers should use --set ON_ERROR_STOP=1.
CREATE FUNCTION pg_temp.expect(label text, passed boolean)
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF passed IS DISTINCT FROM true THEN
    RAISE EXCEPTION 'Reminder test failed: %', label;
  END IF;
END;
$$;


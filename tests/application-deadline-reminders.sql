-- Isolate deadline alerts in checks so ordinary inbox records can coexist.
CREATE TEMP VIEW deadlines AS
SELECT * FROM public.notifications WHERE type = 'application_deadline';
SELECT pg_temp.expect('existing legacy seeker receives one future posting reminder without needing a profile',
  (SELECT count(*) = 1 FROM deadlines WHERE job_id = 10 AND recipient_id = '00000000-0000-4000-8000-000000000001'));
SELECT pg_temp.expect('metadata recruiters and members of the recruiter registry are excluded',
  NOT EXISTS (SELECT FROM deadlines WHERE recipient_id IN (
    '00000000-0000-4000-8000-000000000002', '00000000-0000-4000-8000-000000000003')));
SELECT pg_temp.expect('existing applicant does not receive the reminder for their own application',
  NOT EXISTS (SELECT FROM deadlines WHERE recipient_id = '00000000-0000-4000-8000-000000000004' AND job_id = 10));
SELECT pg_temp.expect('expired, archived, and undated postings do not create reminders',
  NOT EXISTS (SELECT FROM deadlines WHERE job_id IN (11,13,14)));
SELECT pg_temp.expect('winter reminder is at 9 am Montréal on the previous day with an empty application ID',
  (SELECT available_at = TIMESTAMPTZ '2099-01-16 14:00:00+00' AND application_id IS NULL
   FROM deadlines WHERE job_id = 10 AND recipient_id = '00000000-0000-4000-8000-000000000001'));

-- The existing bell query uses available_at <= current time, including exactly 09:00.
SELECT pg_temp.expect('the bell hides the winter reminder at 08:59:59 and shows it at 09:00',
  (SELECT available_at > TIMESTAMPTZ '2099-01-16 13:59:59+00'
      AND available_at <= TIMESTAMPTZ '2099-01-16 14:00:00+00'
   FROM deadlines WHERE job_id = 10 AND recipient_id = '00000000-0000-4000-8000-000000000001'));

-- Editing the title keeps both the unique reminder and the state set by the inbox Mark as read button.
CREATE TEMP TABLE original_alert AS
SELECT id FROM deadlines WHERE job_id = 10 AND recipient_id = '00000000-0000-4000-8000-000000000001';
UPDATE public.notifications SET is_read = true WHERE id = (SELECT id FROM original_alert);
UPDATE public.jobs SET title = 'Renamed posting' WHERE id = 10;
UPDATE public.jobs SET closing_date = closing_date WHERE id = 10;
SELECT pg_temp.expect('refreshing the same deadline preserves its identity and read status without duplicates',
  (SELECT count(*) = 1 AND bool_and(d.id = o.id AND d.is_read AND d.message LIKE '%Renamed posting%')
   FROM deadlines d CROSS JOIN original_alert o WHERE d.job_id = 10
   AND d.recipient_id = '00000000-0000-4000-8000-000000000001'));

-- Summer dates use daylight time; rescheduling makes only the updated deadline unread.
UPDATE public.jobs SET closing_date = DATE '2099-07-17' WHERE id = 10;
SELECT pg_temp.expect('rescheduling keeps one unread summer reminder at 13:00 UTC',
  (SELECT count(*) = 1 AND bool_and(NOT is_read AND available_at = TIMESTAMPTZ '2099-07-16 13:00:00+00')
   FROM deadlines WHERE job_id = 10 AND recipient_id = '00000000-0000-4000-8000-000000000001'));

